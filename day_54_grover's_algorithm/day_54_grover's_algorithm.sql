-- Grover's algorithm: relational model for quantum search experiments.
-- Target: PostgreSQL 14 or later.
-- The database records experiment definitions, oracle targets, executions,
-- iteration measurements, probability distributions, and validation reports.
-- Numerical simulation is performed by the source programs, not SQL.

BEGIN;

CREATE SCHEMA IF NOT EXISTS quantum_search;

SET search_path TO quantum_search, public;

CREATE TABLE IF NOT EXISTS algorithms (
    algorithm_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    algorithm_name TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL,
    query_complexity TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (length(trim(algorithm_name)) > 0)
);

CREATE TABLE IF NOT EXISTS experiments (
    experiment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_name TEXT NOT NULL UNIQUE,
    algorithm_id BIGINT NOT NULL REFERENCES algorithms(algorithm_id),
    qubit_count INTEGER NOT NULL CHECK (qubit_count BETWEEN 1 AND 20),
    expected_marked_count INTEGER NOT NULL CHECK (expected_marked_count > 0),
    search_space_size BIGINT GENERATED ALWAYS AS
        ((1::BIGINT) << qubit_count) STORED,
    requested_iterations INTEGER CHECK (requested_iterations >= 0),
    execution_status TEXT NOT NULL DEFAULT 'configured'
        CHECK (execution_status IN (
            'configured', 'running', 'completed', 'failed'
        )),
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (expected_marked_count <= ((1::BIGINT) << qubit_count))
);

CREATE TABLE IF NOT EXISTS oracle_targets (
    experiment_id BIGINT NOT NULL
        REFERENCES experiments(experiment_id) ON DELETE CASCADE,
    target_state BIGINT NOT NULL CHECK (target_state >= 0),
    target_label TEXT NOT NULL,
    PRIMARY KEY (experiment_id, target_state),
    CHECK (length(trim(target_label)) > 0)
);

CREATE TABLE IF NOT EXISTS executions (
    execution_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id BIGINT NOT NULL
        REFERENCES experiments(experiment_id),
    execution_number INTEGER NOT NULL CHECK (execution_number > 0),
    iteration_count INTEGER NOT NULL CHECK (iteration_count >= 0),
    execution_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (execution_status IN (
            'pending', 'running', 'completed', 'failed'
        )),
    success_probability DOUBLE PRECISION
        CHECK (
            success_probability IS NULL
            OR success_probability BETWEEN 0.0 AND 1.0
        ),
    observed_state BIGINT CHECK (observed_state >= 0),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    failure_reason TEXT,
    UNIQUE (experiment_id, execution_number),
    CHECK (
        completed_at IS NULL
        OR started_at IS NULL
        OR completed_at >= started_at
    ),
    CHECK (
        execution_status <> 'completed'
        OR (
            success_probability IS NOT NULL
            AND observed_state IS NOT NULL
            AND completed_at IS NOT NULL
        )
    ),
    CHECK (
        execution_status <> 'failed'
        OR failure_reason IS NOT NULL
    )
);

CREATE TABLE IF NOT EXISTS state_probabilities (
    execution_id BIGINT NOT NULL
        REFERENCES executions(execution_id) ON DELETE CASCADE,
    basis_state BIGINT NOT NULL CHECK (basis_state >= 0),
    probability DOUBLE PRECISION NOT NULL
        CHECK (
            probability >= 0.0
            AND probability <= 1.0
            AND probability <> 'NaN'::DOUBLE PRECISION
            AND probability <> 'Infinity'::DOUBLE PRECISION
        ),
    PRIMARY KEY (execution_id, basis_state)
);

CREATE TABLE IF NOT EXISTS validation_reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id BIGINT NOT NULL REFERENCES executions(execution_id),
    validation_type TEXT NOT NULL
        CHECK (validation_type IN (
            'normalization', 'marked_probability', 'domain', 'policy'
        )),
    passed BOOLEAN NOT NULL,
    measured_value DOUBLE PRECISION,
    expected_value DOUBLE PRECISION,
    details TEXT NOT NULL,
    checked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_experiments_status_created
    ON experiments (execution_status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_executions_experiment_status
    ON executions (experiment_id, execution_status);

CREATE INDEX IF NOT EXISTS idx_validation_reports_execution
    ON validation_reports (execution_id, checked_at DESC);

