CREATE OR REPLACE FUNCTION validate_oracle_target()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    domain_size BIGINT;
BEGIN
    SELECT search_space_size
    INTO domain_size
    FROM experiments
    WHERE experiment_id = NEW.experiment_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Experiment % does not exist', NEW.experiment_id;
    END IF;

    IF NEW.target_state >= domain_size THEN
        RAISE EXCEPTION
            'Target state % is outside experiment domain [0, %)',
            NEW.target_state, domain_size;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_oracle_target ON oracle_targets;

CREATE TRIGGER trg_validate_oracle_target
BEFORE INSERT OR UPDATE ON oracle_targets
FOR EACH ROW EXECUTE FUNCTION validate_oracle_target();

CREATE OR REPLACE FUNCTION validate_execution_domain()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    domain_size BIGINT;
    marked_count INTEGER;
BEGIN
    SELECT search_space_size, expected_marked_count
    INTO domain_size, marked_count
    FROM experiments
    WHERE experiment_id = NEW.experiment_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Experiment % does not exist', NEW.experiment_id;
    END IF;

    IF NEW.observed_state IS NOT NULL
       AND NEW.observed_state >= domain_size THEN
        RAISE EXCEPTION 'Observed state is outside the search domain';
    END IF;

    IF NEW.iteration_count < 0 THEN
        RAISE EXCEPTION 'Iteration count cannot be negative';
    END IF;

    IF NEW.execution_status = 'completed' THEN
        IF NEW.success_probability IS NULL
           OR NEW.observed_state IS NULL
           OR NEW.completed_at IS NULL THEN
            RAISE EXCEPTION
                'Completed executions require a result and completion timestamp';
        END IF;

        IF (
            SELECT count(*)
            FROM oracle_targets
            WHERE experiment_id = NEW.experiment_id
        ) <> marked_count THEN
            RAISE EXCEPTION
                'Configured oracle target count does not match expected marked count';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_execution_domain ON executions;

CREATE TRIGGER trg_validate_execution_domain
BEFORE INSERT OR UPDATE ON executions
FOR EACH ROW EXECUTE FUNCTION validate_execution_domain();

CREATE OR REPLACE FUNCTION evaluate_execution(
    p_execution_id BIGINT,
    p_normalization_tolerance DOUBLE PRECISION DEFAULT 0.000001
)
RETURNS TABLE (
    execution_id BIGINT,
    probability_sum DOUBLE PRECISION,
    computed_marked_probability DOUBLE PRECISION,
    normalization_passed BOOLEAN,
    marked_probability_passed BOOLEAN
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_experiment_id BIGINT;
    v_domain_size BIGINT;
    v_probability_sum DOUBLE PRECISION;
    v_marked_probability DOUBLE PRECISION;
    v_expected_probability DOUBLE PRECISION;
    v_normalization_passed BOOLEAN;
    v_marked_probability_passed BOOLEAN;
BEGIN
    IF p_normalization_tolerance < 0
       OR p_normalization_tolerance > 0.01 THEN
        RAISE EXCEPTION 'Normalization tolerance must be between 0 and 0.01';
    END IF;

    SELECT e.experiment_id, e.search_space_size
    INTO v_experiment_id, v_domain_size
    FROM executions AS x
    JOIN experiments AS e USING (experiment_id)
    WHERE x.execution_id = p_execution_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Execution % does not exist', p_execution_id;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM state_probabilities AS p
        WHERE p.execution_id = p_execution_id
          AND p.basis_state >= v_domain_size
    ) THEN
        RAISE EXCEPTION 'A stored basis state is outside the search domain';
    END IF;

    SELECT COALESCE(sum(probability), 0.0)
    INTO v_probability_sum
    FROM state_probabilities
    WHERE state_probabilities.execution_id = p_execution_id;

    SELECT COALESCE(sum(p.probability), 0.0)
    INTO v_marked_probability
    FROM state_probabilities AS p
    JOIN oracle_targets AS t
      ON t.experiment_id = v_experiment_id
     AND t.target_state = p.basis_state
    WHERE p.execution_id = p_execution_id;

    SELECT success_probability
    INTO v_expected_probability
    FROM executions
    WHERE executions.execution_id = p_execution_id;

    v_normalization_passed :=
        abs(v_probability_sum - 1.0) <= p_normalization_tolerance;

    v_marked_probability_passed :=
        v_expected_probability IS NOT NULL
        AND abs(v_marked_probability - v_expected_probability)
            <= p_normalization_tolerance;

    INSERT INTO validation_reports (
        execution_id, validation_type, passed, measured_value,
        expected_value, details
    )
    VALUES
    (
        p_execution_id,
        'normalization',
        v_normalization_passed,
        v_probability_sum,
        1.0,
        'Sum of stored basis-state probabilities.'
    ),
    (
        p_execution_id,
        'marked_probability',
        v_marked_probability_passed,
        v_marked_probability,
        v_expected_probability,
        'Sum of probabilities for marked basis states.'
    );

    RETURN QUERY
    SELECT
        p_execution_id,
        v_probability_sum,
        v_marked_probability,
        v_normalization_passed,
        v_marked_probability_passed;
END;
$$;

CREATE OR REPLACE VIEW experiment_execution_report AS
SELECT
    e.experiment_id,
    e.experiment_name,
    e.qubit_count,
    e.search_space_size,
    e.expected_marked_count,
    e.execution_status AS experiment_status,
    x.execution_id,
    x.execution_number,
    x.iteration_count,
    x.execution_status AS run_status,
    x.success_probability,
    x.observed_state,
    COALESCE(probability_totals.probability_sum, 0.0)
        AS stored_probability_sum,
    COALESCE(target_counts.actual_target_count, 0)
        AS actual_target_count
FROM experiments AS e
LEFT JOIN executions AS x USING (experiment_id)
LEFT JOIN LATERAL (
    SELECT sum(p.probability) AS probability_sum
    FROM state_probabilities AS p
    WHERE p.execution_id = x.execution_id
) AS probability_totals ON TRUE
LEFT JOIN LATERAL (
    SELECT count(*) AS actual_target_count
    FROM oracle_targets AS t
    WHERE t.experiment_id = e.experiment_id
) AS target_counts ON TRUE;

-- Retrieval: inspect experiment configuration and execution state.
SELECT *
FROM experiment_execution_report
ORDER BY experiment_id, execution_number;

-- Evaluation: validate normalization and agreement with the recorded
-- probability of measuring a marked state.
SELECT evaluate_execution(execution_id)
FROM executions
WHERE experiment_id = (
    SELECT experiment_id
    FROM experiments
    WHERE experiment_name = 'single_target_4_qubits'
)
AND execution_number = 1;

-- Aggregation: compare average observed success probabilities by qubit count.
SELECT
    e.qubit_count,
    count(x.execution_id) AS execution_count,
    avg(x.success_probability) AS mean_success_probability,
    min(x.iteration_count) AS minimum_iterations,
    max(x.iteration_count) AS maximum_iterations
FROM experiments AS e
JOIN executions AS x USING (experiment_id)
WHERE x.execution_status = 'completed'
GROUP BY e.qubit_count
ORDER BY e.qubit_count;

-- State distribution: marked states should collectively match the recorded
-- success probability for an ideal execution.
SELECT
    p.basis_state,
    t.target_label,
    p.probability,
    (t.target_state IS NOT NULL) AS is_marked
FROM state_probabilities AS p
LEFT JOIN oracle_targets AS t
    ON t.experiment_id = (
        SELECT experiment_id
        FROM executions
        WHERE execution_id = p.execution_id
    )
   AND t.target_state = p.basis_state
WHERE p.execution_id = (
    SELECT execution_id
    FROM executions
    WHERE experiment_id = (
        SELECT experiment_id
        FROM experiments
        WHERE experiment_name = 'single_target_4_qubits'
    )
    AND execution_number = 1
)
ORDER BY p.basis_state;

-- Demonstrate transactional rollback for an invalid oracle target.
-- The exception is caught in a subtransaction, allowing the script to continue.
DO $$
DECLARE
    v_experiment_id BIGINT;
BEGIN
    SELECT experiment_id
    INTO v_experiment_id
    FROM quantum_search.experiments
    WHERE experiment_name = 'single_target_4_qubits';

    BEGIN
        INSERT INTO quantum_search.oracle_targets (
            experiment_id, target_state, target_label
        )
        VALUES (v_experiment_id, 16, 'invalid-out-of-range-target');

        RAISE EXCEPTION 'Expected invalid target to be rejected';
    EXCEPTION
        WHEN check_violation OR raise_exception THEN
            RAISE NOTICE 'Invalid target rejected; subtransaction rolled back.';
    END;
END;
$$;

COMMIT;
