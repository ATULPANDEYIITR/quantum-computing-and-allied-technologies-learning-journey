-- Validate that stored targets remain inside the experiment's state space.
CREATE OR REPLACE FUNCTION validate_marked_state()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    permitted_states INTEGER;
BEGIN
    SELECT state_count
    INTO permitted_states
    FROM experiments
    WHERE experiment_id = NEW.experiment_id;

    IF permitted_states IS NULL THEN
        RAISE EXCEPTION 'Experiment % does not exist', NEW.experiment_id;
    END IF;

    IF NEW.state_value >= permitted_states THEN
        RAISE EXCEPTION 'State % exceeds experiment state space %',
            NEW.state_value, permitted_states;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_marked_state ON marked_states;
CREATE TRIGGER trg_validate_marked_state
BEFORE INSERT OR UPDATE ON marked_states
FOR EACH ROW EXECUTE FUNCTION validate_marked_state();

-- Runs are historical records; reject invalid measurements before insertion.
CREATE OR REPLACE FUNCTION validate_execution_run()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    permitted_states INTEGER;
    target_count INTEGER;
BEGIN
    SELECT state_count, marked_count
    INTO permitted_states, target_count
    FROM experiments
    WHERE experiment_id = NEW.experiment_id;

    IF permitted_states IS NULL THEN
        RAISE EXCEPTION 'Unknown experiment %', NEW.experiment_id;
    END IF;

    IF NEW.measured_state >= permitted_states THEN
        RAISE EXCEPTION 'Measured state % is outside the search space',
            NEW.measured_state;
    END IF;

    IF NEW.execution_status = 'completed' THEN
        SELECT COUNT(*) INTO target_count
        FROM marked_states
        WHERE experiment_id = NEW.experiment_id;

        IF target_count = 0 THEN
            RAISE EXCEPTION 'Completed run requires recorded marked states';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_execution_run ON execution_runs;
CREATE TRIGGER trg_validate_execution_run
BEFORE INSERT OR UPDATE ON execution_runs
FOR EACH ROW EXECUTE FUNCTION validate_execution_run();

-- Compute a recommended iteration count for a known number of marked states.
CREATE OR REPLACE FUNCTION recommended_iterations(
    p_state_count INTEGER,
    p_marked_count INTEGER
)
RETURNS INTEGER
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $$
DECLARE
    theta DOUBLE PRECISION;
BEGIN
    IF p_state_count < 1
       OR p_marked_count < 0
       OR p_marked_count > p_state_count THEN
        RAISE EXCEPTION 'Invalid state or marked-state count';
    END IF;

    IF p_marked_count = 0 OR p_marked_count = p_state_count THEN
        RETURN 0;
    END IF;

    theta := asin(sqrt(p_marked_count::DOUBLE PRECISION / p_state_count));
    RETURN GREATEST(0, round(pi() / (4.0 * theta) - 0.5)::INTEGER);
END;
$$;

-- Merge-like reporting is not required here: search success is the probability
-- mass assigned to marked basis states after amplitude amplification.
CREATE OR REPLACE VIEW experiment_report AS
SELECT
    e.experiment_id,
    e.experiment_name,
    a.algorithm_name,
    e.qubits,
    e.state_count,
    e.marked_count,
    recommended_iterations(e.state_count, e.marked_count)
        AS recommended_iterations,
    COUNT(r.run_id) AS total_runs,
    COUNT(r.run_id) FILTER (
        WHERE r.execution_status = 'completed'
    ) AS completed_runs,
    COUNT(r.run_id) FILTER (
        WHERE r.execution_status = 'failed'
    ) AS failed_runs,
    AVG(r.success_probability) FILTER (
        WHERE r.execution_status = 'completed'
    ) AS average_success_probability
FROM experiments e
JOIN algorithms a ON a.algorithm_id = e.algorithm_id
LEFT JOIN execution_runs r ON r.experiment_id = e.experiment_id
GROUP BY
    e.experiment_id, e.experiment_name, a.algorithm_name,
    e.qubits, e.state_count, e.marked_count;

