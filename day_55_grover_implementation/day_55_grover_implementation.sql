-- PostgreSQL 14+
-- Relational model for Grover search experiments, circuit configurations,
-- execution runs, and probability-based validation.

BEGIN;

CREATE SCHEMA IF NOT EXISTS quantum_search;
SET LOCAL search_path TO quantum_search, public;

CREATE TABLE IF NOT EXISTS algorithms (
    algorithm_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    algorithm_name TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL,
    query_complexity TEXT NOT NULL,
    requires_oracle BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS experiments (
    experiment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_name TEXT NOT NULL,
    qubits INTEGER NOT NULL CHECK (qubits BETWEEN 1 AND 20),
    marked_count INTEGER NOT NULL CHECK (marked_count BETWEEN 1 AND 1048576),
    state_count INTEGER GENERATED ALWAYS AS (1 << qubits) STORED,
    requested_iterations INTEGER CHECK (
        requested_iterations BETWEEN 0 AND 100000
    ),
    algorithm_id BIGINT NOT NULL REFERENCES algorithms(algorithm_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (marked_count <= (1 << qubits))
);

CREATE TABLE IF NOT EXISTS marked_states (
    experiment_id BIGINT NOT NULL
        REFERENCES experiments(experiment_id) ON DELETE CASCADE,
    state_value INTEGER NOT NULL CHECK (state_value >= 0),
    PRIMARY KEY (experiment_id, state_value)
);

CREATE TABLE IF NOT EXISTS execution_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id BIGINT NOT NULL
        REFERENCES experiments(experiment_id) ON DELETE CASCADE,
    iterations INTEGER NOT NULL CHECK (iterations BETWEEN 0 AND 100000),
    measured_state INTEGER NOT NULL CHECK (measured_state >= 0),
    success_probability DOUBLE PRECISION NOT NULL CHECK (
        success_probability BETWEEN 0.0 AND 1.0
    ),
    state_norm DOUBLE PRECISION NOT NULL CHECK (
        state_norm BETWEEN 0.99 AND 1.01
    ),
    execution_status TEXT NOT NULL CHECK (
        execution_status IN ('completed', 'failed', 'rejected')
    ),
    failure_reason TEXT,
    executed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        (execution_status = 'completed' AND failure_reason IS NULL)
        OR
        (execution_status <> 'completed' AND failure_reason IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS execution_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES execution_runs(run_id) ON DELETE CASCADE,
    event_type TEXT NOT NULL CHECK (
        event_type IN ('initialized', 'oracle_applied', 'diffusion_applied',
                       'measured', 'validation_failed')
    ),
    event_detail JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_runs_experiment_time
    ON execution_runs (experiment_id, executed_at DESC);

CREATE INDEX IF NOT EXISTS idx_events_run_time
    ON execution_events (run_id, created_at);

CREATE INDEX IF NOT EXISTS idx_runs_failed
    ON execution_runs (executed_at DESC)
    WHERE execution_status = 'failed';

