-- Query 1: retrieve the experiment plan and optimized iteration count.
SELECT
    experiment_name,
    state_count,
    marked_count,
    recommended_iterations(state_count, marked_count) AS optimal_iterations
FROM experiments
ORDER BY experiment_id;

-- Query 2: report actual recorded execution outcomes.
SELECT *
FROM experiment_report
ORDER BY experiment_id;

-- Query 3: determine whether each measured state was a target.
SELECT
    r.run_id,
    e.experiment_name,
    r.measured_state,
    EXISTS (
        SELECT 1
        FROM marked_states m
        WHERE m.experiment_id = r.experiment_id
          AND m.state_value = r.measured_state
    ) AS found_target,
    r.success_probability,
    r.execution_status
FROM execution_runs r
JOIN experiments e ON e.experiment_id = r.experiment_id
ORDER BY r.run_id;

-- Query 4: investigate failed runs and their event history.
SELECT
    r.run_id,
    r.failure_reason,
    ev.event_type,
    ev.event_detail,
    ev.created_at
FROM execution_runs r
LEFT JOIN execution_events ev ON ev.run_id = r.run_id
WHERE r.execution_status = 'failed'
ORDER BY r.run_id, ev.created_at;

-- Transactional demonstration: invalid state insertion rolls back as one unit.
SAVEPOINT invalid_target_demo;
DO $$
BEGIN
    BEGIN
        INSERT INTO marked_states (experiment_id, state_value)
        VALUES (1, 16);
    EXCEPTION WHEN check_violation OR raise_exception THEN
        RAISE NOTICE 'Invalid marked state rejected as expected.';
    END;
END;
$$;
ROLLBACK TO SAVEPOINT invalid_target_demo;
RELEASE SAVEPOINT invalid_target_demo;

COMMIT;
