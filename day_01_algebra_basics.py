# Day 00: Algebra Basics for Quantum Computing

print("DAY 01 - ALGEBRA BASICS FOR QUANTUM COMPUTING")

print("\n1. NUMBERS")

a = 10
b = 5

print("a =", a)
print("b =", b)


print("\n2. BASIC ARITHMETIC OPERATIONS")

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)


print("\n3. VARIABLES")

x = 4

print("x =", x)


print("\n4. SIMPLE ALGEBRAIC EXPRESSION")

# Expression: 2x + 3

result = 2 * x + 3

print("For x =", x)
print("2x + 3 =", result)


print("\n5. ANOTHER ALGEBRAIC EXPRESSION")

# Expression: x² + 2x + 1

result = x ** 2 + 2 * x + 1

print("For x =", x)
print("x² + 2x + 1 =", result)


