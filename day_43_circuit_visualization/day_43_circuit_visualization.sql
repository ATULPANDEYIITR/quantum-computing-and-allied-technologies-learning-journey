-- PostgreSQL 14+
-- Circuit Visualization and Analysis
--
-- Relational model for schematic editing, circuit connectivity,
-- component properties, DC analysis runs, calculated measurements,
-- and visualization artifacts.
--
-- The schema stores component orientation and connectivity explicitly.
-- Analysis results are stored separately from design definitions so that
-- successive runs do not overwrite historical measurements.

BEGIN;

CREATE SCHEMA IF NOT EXISTS circuit_lab;
SET search_path TO circuit_lab, public;

CREATE TABLE IF NOT EXISTS circuits (
    circuit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circuit_name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    ground_node TEXT NOT NULL DEFAULT '0',
    revision INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT circuits_name_nonempty CHECK (length(trim(circuit_name)) > 0),
    CONSTRAINT circuits_ground_nonempty CHECK (length(trim(ground_node)) > 0),
    UNIQUE (circuit_name, revision)
);

CREATE TABLE IF NOT EXISTS circuit_nodes (
    node_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circuit_id BIGINT NOT NULL REFERENCES circuits(circuit_id)
        ON DELETE CASCADE,
    node_name TEXT NOT NULL,
    is_ground BOOLEAN NOT NULL DEFAULT FALSE,
    schematic_x NUMERIC(10, 2),
    schematic_y NUMERIC(10, 2),
    CONSTRAINT circuit_nodes_name_nonempty CHECK (length(trim(node_name)) > 0),
    UNIQUE (circuit_id, node_name),
    UNIQUE (circuit_id, node_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS one_ground_per_circuit
    ON circuit_nodes(circuit_id)
    WHERE is_ground;

CREATE TABLE IF NOT EXISTS components (
    component_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circuit_id BIGINT NOT NULL REFERENCES circuits(circuit_id)
        ON DELETE CASCADE,
    component_name TEXT NOT NULL,
    component_type TEXT NOT NULL CHECK (
        component_type IN (
            'RESISTOR',
            'VOLTAGE_SOURCE',
            'CURRENT_SOURCE',
            'CAPACITOR',
            'INDUCTOR',
            'DIODE'
        )
    ),
    terminal_a_id BIGINT NOT NULL,
    terminal_b_id BIGINT NOT NULL,
    value_si DOUBLE PRECISION NOT NULL,
    unit_symbol TEXT NOT NULL,
    rated_power_w DOUBLE PRECISION,
    schematic_x NUMERIC(10, 2),
    schematic_y NUMERIC(10, 2),
    rotation_degrees INTEGER NOT NULL DEFAULT 0,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT component_name_nonempty CHECK (length(trim(component_name)) > 0),
    CONSTRAINT component_unit_nonempty CHECK (length(trim(unit_symbol)) > 0),
    CONSTRAINT component_terminals_differ CHECK (terminal_a_id <> terminal_b_id),
    CONSTRAINT component_value_finite CHECK (
        value_si > '-Infinity'::DOUBLE PRECISION
        AND value_si < 'Infinity'::DOUBLE PRECISION
    ),
    CONSTRAINT component_rating_positive CHECK (
        rated_power_w IS NULL OR rated_power_w > 0
    ),
    CONSTRAINT components_rotation_range CHECK (
        rotation_degrees BETWEEN 0 AND 359
    ),
    FOREIGN KEY (circuit_id, terminal_a_id)
        REFERENCES circuit_nodes(circuit_id, node_id),
    FOREIGN KEY (circuit_id, terminal_b_id)
        REFERENCES circuit_nodes(circuit_id, node_id),
    UNIQUE (circuit_id, component_name)
);

CREATE INDEX IF NOT EXISTS components_by_circuit_type
    ON components(circuit_id, component_type)
    WHERE enabled;

CREATE TABLE IF NOT EXISTS analysis_runs (
    analysis_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circuit_id BIGINT NOT NULL REFERENCES circuits(circuit_id)
        ON DELETE CASCADE,
    circuit_revision INTEGER NOT NULL CHECK (circuit_revision > 0),
    analysis_type TEXT NOT NULL CHECK (
        analysis_type IN ('DC_OPERATING_POINT', 'AC_SWEEP', 'TRANSIENT')
    ),
    analysis_status TEXT NOT NULL DEFAULT 'PENDING' CHECK (
        analysis_status IN ('PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED')
    ),
    solver_name TEXT NOT NULL,
    solver_version TEXT NOT NULL,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT completed_run_has_end_time CHECK (
        analysis_status NOT IN ('SUCCEEDED', 'FAILED')
        OR completed_at IS NOT NULL
    ),
    CONSTRAINT failed_run_has_reason CHECK (
        analysis_status <> 'FAILED'
        OR NULLIF(trim(error_message), '') IS NOT NULL
    )
);

CREATE INDEX IF NOT EXISTS analysis_runs_recent
    ON analysis_runs(circuit_id, created_at DESC);

CREATE TABLE IF NOT EXISTS node_measurements (
    analysis_id BIGINT NOT NULL REFERENCES analysis_runs(analysis_id)
        ON DELETE CASCADE,
    node_id BIGINT NOT NULL REFERENCES circuit_nodes(node_id)
        ON DELETE CASCADE,
    voltage_v DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (analysis_id, node_id),
    CONSTRAINT node_voltage_finite CHECK (
        voltage_v > '-Infinity'::DOUBLE PRECISION
        AND voltage_v < 'Infinity'::DOUBLE PRECISION
    )
);

CREATE TABLE IF NOT EXISTS branch_measurements (
    analysis_id BIGINT NOT NULL REFERENCES analysis_runs(analysis_id)
        ON DELETE CASCADE,
    component_id BIGINT NOT NULL REFERENCES components(component_id)
        ON DELETE CASCADE,
    voltage_v DOUBLE PRECISION NOT NULL,
    current_a DOUBLE PRECISION NOT NULL,
    power_w DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (analysis_id, component_id),
    CONSTRAINT branch_voltage_finite CHECK (
        voltage_v > '-Infinity'::DOUBLE PRECISION
        AND voltage_v < 'Infinity'::DOUBLE PRECISION
    ),
    CONSTRAINT branch_current_finite CHECK (
        current_a > '-Infinity'::DOUBLE PRECISION
        AND current_a < 'Infinity'::DOUBLE PRECISION
    ),
    CONSTRAINT branch_power_finite CHECK (
        power_w > '-Infinity'::DOUBLE PRECISION
        AND power_w < 'Infinity'::DOUBLE PRECISION
    )
);

CREATE TABLE IF NOT EXISTS schematic_exports (
    export_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circuit_id BIGINT NOT NULL REFERENCES circuits(circuit_id)
        ON DELETE CASCADE,
    circuit_revision INTEGER NOT NULL CHECK (circuit_revision > 0),
    export_format TEXT NOT NULL CHECK (
        export_format IN ('SVG', 'JSON', 'NETLIST')
    ),
    export_status TEXT NOT NULL CHECK (
        export_status IN ('GENERATED', 'FAILED')
    ),
    storage_uri TEXT,
    content_sha256 TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT export_location_required CHECK (
        export_status <> 'GENERATED'
        OR NULLIF(trim(storage_uri), '') IS NOT NULL
    ),
    CONSTRAINT export_hash_format CHECK (
        content_sha256 IS NULL
        OR content_sha256 ~ '^[0-9a-f]{64}$'
    )
);

CREATE TABLE IF NOT EXISTS electrical_limits (
    limit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circuit_id BIGINT NOT NULL REFERENCES circuits(circuit_id)
        ON DELETE CASCADE,
    component_id BIGINT REFERENCES components(component_id)
        ON DELETE CASCADE,
    limit_name TEXT NOT NULL CHECK (length(trim(limit_name)) > 0),
    metric TEXT NOT NULL CHECK (
        metric IN ('CURRENT_A', 'DISSIPATION_W', 'VOLTAGE_V')
    ),
    maximum_value DOUBLE PRECISION NOT NULL CHECK (
        maximum_value > 0
        AND maximum_value < 'Infinity'::DOUBLE PRECISION
    ),
    severity TEXT NOT NULL CHECK (severity IN ('WARNING', 'CRITICAL')),
    UNIQUE (circuit_id, component_id, limit_name)
);

-- Ensure that a node declared as ground uses the circuit's configured
-- ground identifier. A normal CHECK constraint cannot inspect another table.
CREATE OR REPLACE FUNCTION validate_circuit_ground()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    configured_ground TEXT;
BEGIN
    SELECT ground_node
    INTO configured_ground
    FROM circuits
    WHERE circuit_id = NEW.circuit_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Circuit % does not exist', NEW.circuit_id;
    END IF;

    IF NEW.is_ground AND NEW.node_name <> configured_ground THEN
        RAISE EXCEPTION
            'Ground node must be named %', configured_ground;
    END IF;

    IF NOT NEW.is_ground AND NEW.node_name = configured_ground THEN
        RAISE EXCEPTION
            'Configured ground node % must be marked as ground',
            configured_ground;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS circuit_ground_validation ON circuit_nodes;

CREATE TRIGGER circuit_ground_validation
BEFORE INSERT OR UPDATE OF circuit_id, node_name, is_ground
ON circuit_nodes
FOR EACH ROW
EXECUTE FUNCTION validate_circuit_ground();

-- Verify that a component value has a sensible sign for the supported
-- component type. Signed voltage-source values encode source polarity.
CREATE OR REPLACE FUNCTION validate_component_value()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.component_type IN ('RESISTOR', 'CAPACITOR', 'INDUCTOR')
       AND NEW.value_si <= 0 THEN
        RAISE EXCEPTION
            '% requires a positive component value', NEW.component_type;
    END IF;

    IF NEW.component_type = 'DIODE' AND NEW.value_si < 0 THEN
        RAISE EXCEPTION 'Diode model parameter cannot be negative';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS component_value_validation ON components;

CREATE TRIGGER component_value_validation
BEFORE INSERT OR UPDATE OF component_type, value_si
ON components
FOR EACH ROW
EXECUTE FUNCTION validate_component_value();

-- Store the revision and reject an analysis that references an impossible
-- circuit revision. Historical analyses may legitimately use older revisions.
CREATE OR REPLACE FUNCTION validate_analysis_revision()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    current_revision INTEGER;
BEGIN
    SELECT revision
    INTO current_revision
    FROM circuits
    WHERE circuit_id = NEW.circuit_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Circuit % does not exist', NEW.circuit_id;
    END IF;

    IF NEW.circuit_revision > current_revision THEN
        RAISE EXCEPTION
            'Analysis revision % exceeds current circuit revision %',
            NEW.circuit_revision, current_revision;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS analysis_revision_validation ON analysis_runs;

CREATE TRIGGER analysis_revision_validation
BEFORE INSERT OR UPDATE OF circuit_id, circuit_revision
ON analysis_runs
FOR EACH ROW
EXECUTE FUNCTION validate_analysis_revision();

-- An analysis can be marked successful only when it has a completion time.
-- Measurements are written by the solver application in one transaction.
CREATE OR REPLACE VIEW circuit_component_inventory AS
SELECT
    c.circuit_id,
    c.circuit_name,
    c.revision,
    n.node_name AS terminal_a,
    m.node_name AS terminal_b,
    p.component_name,
    p.component_type,
    p.value_si,
    p.unit_symbol,
    p.rated_power_w,
    p.enabled
FROM circuits c
JOIN components p ON p.circuit_id = c.circuit_id
JOIN circuit_nodes n ON n.node_id = p.terminal_a_id
JOIN circuit_nodes m ON m.node_id = p.terminal_b_id;

CREATE OR REPLACE VIEW latest_analysis_status AS
SELECT DISTINCT ON (circuit_id)
    circuit_id,
    analysis_id,
    circuit_revision,
    analysis_type,
    analysis_status,
    created_at,
    completed_at,
    error_message
FROM analysis_runs
ORDER BY circuit_id, created_at DESC, analysis_id DESC;

CREATE OR REPLACE VIEW resistor_power_report AS
SELECT
    ar.analysis_id,
    ar.circuit_id,
    ar.circuit_revision,
    p.component_name,
    bm.voltage_v,
    bm.current_a,
    bm.power_w,
    p.rated_power_w,
    CASE
        WHEN p.rated_power_w IS NOT NULL
         AND bm.power_w > p.rated_power_w
        THEN 'RATING_EXCEEDED'
        ELSE 'WITHIN_RECORDED_RATING'
    END AS rating_status
FROM branch_measurements bm
JOIN analysis_runs ar ON ar.analysis_id = bm.analysis_id
JOIN components p ON p.component_id = bm.component_id
WHERE p.component_type = 'RESISTOR';

