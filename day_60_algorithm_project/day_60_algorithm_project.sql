-- Evaluation: compare observed measurement frequencies with recorded probabilities.
SELECT
    e.experiment_id,
    e.experiment_name,
    m.bitstring,
    count(*) AS recorded_shots,
    round(avg(m.outcome_probability)::numeric, 6) AS mean_recorded_probability
