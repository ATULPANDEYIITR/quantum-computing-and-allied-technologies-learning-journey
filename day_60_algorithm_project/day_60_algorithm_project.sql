-- Quantum experiment laboratory: algorithms, execution records and measurements.
-- Compatible with PostgreSQL 14 and later.

DROP SCHEMA IF EXISTS quantum_lab CASCADE;
CREATE SCHEMA quantum_lab;
SET search_path TO quantum_lab, public;

-- The catalog distinguishes algorithms from the backend used to execute them.
CREATE TABLE algorithm (
    algorithm_code text PRIMARY KEY,
    display_name text NOT NULL UNIQUE,
    description text NOT NULL,
    computational_model text NOT NULL
        CHECK (computational_model IN ('ORACLE', 'SEARCH', 'PHASE_ESTIMATION'))
);

CREATE TABLE quantum_backend (
    backend_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    backend_name text NOT NULL UNIQUE,
    backend_type text NOT NULL
        CHECK (backend_type IN ('STATE_VECTOR', 'GATE_SIMULATOR', 'QUANTUM_HARDWARE')),
    max_qubits integer NOT NULL CHECK (max_qubits BETWEEN 1 AND 1000),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE experiment (
    experiment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_name text NOT NULL CHECK (length(trim(experiment_name)) > 0),
    algorithm_code text NOT NULL REFERENCES algorithm(algorithm_code),
    backend_id bigint NOT NULL REFERENCES quantum_backend(backend_id),
    requested_by text NOT NULL CHECK (length(trim(requested_by)) > 0),
    qubit_count integer NOT NULL CHECK (qubit_count BETWEEN 1 AND 1000),
    shots integer NOT NULL CHECK (shots BETWEEN 1 AND 1000000),
    parameters jsonb NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(parameters) = 'object'),
    random_seed bigint,
    status text NOT NULL DEFAULT 'QUEUED'
        CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED', 'CANCELLED')),
    error_message text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    started_at timestamptz,
    completed_at timestamptz,
    CHECK (
        (status = 'QUEUED' AND started_at IS NULL AND completed_at IS NULL)
        OR
        (status = 'RUNNING' AND started_at IS NOT NULL AND completed_at IS NULL)
        OR
        (status IN ('SUCCEEDED', 'FAILED')
            AND started_at IS NOT NULL
            AND completed_at IS NOT NULL)
        OR
        (status = 'CANCELLED' AND completed_at IS NOT NULL)
    ),
    CHECK (status <> 'FAILED' OR error_message IS NOT NULL)
);

CREATE INDEX experiment_status_created_idx
    ON experiment (status, created_at DESC);

CREATE INDEX experiment_algorithm_created_idx
    ON experiment (algorithm_code, created_at DESC);

CREATE INDEX experiment_parameters_gin_idx
    ON experiment USING gin (parameters jsonb_path_ops);

-- Algorithm-specific parameter checks and backend capacity enforcement.
CREATE OR REPLACE FUNCTION validate_experiment_configuration()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_backend_capacity integer;
    v_backend_active boolean;
    v_required_qubits integer;
    v_secret text;
    v_marked jsonb;
    v_item jsonb;
    v_phase numeric;
BEGIN
    SELECT max_qubits, is_active
      INTO v_backend_capacity, v_backend_active
      FROM quantum_backend
     WHERE backend_id = NEW.backend_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown quantum backend %', NEW.backend_id;
    END IF;

    IF NOT v_backend_active THEN
        RAISE EXCEPTION 'Backend % is inactive', NEW.backend_id;
    END IF;

    v_required_qubits := NEW.qubit_count;

    CASE NEW.algorithm_code
        WHEN 'DEUTSCH_JOZSA' THEN
            IF NEW.parameters->>'oracle' NOT IN (
                'constant-zero', 'constant-one', 'balanced-parity'
            ) THEN
                RAISE EXCEPTION
                    'Deutsch-Jozsa requires oracle constant-zero, constant-one or balanced-parity';
            END IF;

        WHEN 'BERNSTEIN_VAZIRANI' THEN
            v_secret := NEW.parameters->>'secret';

            IF v_secret IS NULL
               OR v_secret !~ '^[01]+$'
               OR length(v_secret) <> NEW.qubit_count THEN
                RAISE EXCEPTION
                    'Bernstein-Vazirani secret must be a binary string matching qubit_count';
            END IF;

        WHEN 'GROVER' THEN
            v_marked := NEW.parameters->'marked_states';

            IF v_marked IS NULL
               OR jsonb_typeof(v_marked) <> 'array'
               OR jsonb_array_length(v_marked) = 0 THEN
                RAISE EXCEPTION
                    'Grover requires a non-empty marked_states array';
            END IF;

            FOR v_item IN SELECT value FROM jsonb_array_elements(v_marked)
            LOOP
                IF jsonb_typeof(v_item) <> 'number'
                   OR (v_item #>> '{}')::numeric < 0
                   OR (v_item #>> '{}')::numeric >= power(2::numeric, NEW.qubit_count) THEN
                    RAISE EXCEPTION
                        'Grover marked states must be non-negative basis indices within the register';
                END IF;
            END LOOP;

            IF (
                SELECT count(*) <> count(DISTINCT value)
                  FROM jsonb_array_elements_text(v_marked)
            ) THEN
                RAISE EXCEPTION 'Grover marked_states must not contain duplicates';
            END IF;

        WHEN 'PHASE_ESTIMATION' THEN
            IF NEW.parameters->>'phase' IS NULL THEN
                RAISE EXCEPTION 'Phase estimation requires a phase parameter';
            END IF;

            v_phase := (NEW.parameters->>'phase')::numeric;

            IF v_phase < 0 OR v_phase >= 1 THEN
                RAISE EXCEPTION 'Phase must lie in [0, 1)';
            END IF;

            -- The phase-estimation model includes one target eigenstate qubit.
            v_required_qubits := NEW.qubit_count + 1;

        ELSE
            RAISE EXCEPTION 'Unsupported algorithm code %', NEW.algorithm_code;
    END CASE;

    IF v_required_qubits > v_backend_capacity THEN
        RAISE EXCEPTION
            'Requested circuit needs % qubits; backend capacity is %',
            v_required_qubits, v_backend_capacity;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER experiment_configuration_guard
BEFORE INSERT OR UPDATE OF algorithm_code, backend_id, qubit_count, parameters
ON experiment
FOR EACH ROW
EXECUTE FUNCTION validate_experiment_configuration();

-- Experiment states are explicit. Terminal states cannot be reopened or rewritten.
CREATE OR REPLACE FUNCTION enforce_experiment_state_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'QUEUED' THEN
            RAISE EXCEPTION 'Experiments must be created in QUEUED state';
        END IF;
        RETURN NEW;
    END IF;

    IF OLD.status = NEW.status THEN
        RETURN NEW;
    END IF;

    IF OLD.status IN ('SUCCEEDED', 'FAILED', 'CANCELLED') THEN
        RAISE EXCEPTION 'Terminal experiment state % cannot be changed', OLD.status;
    END IF;

    IF OLD.status = 'QUEUED'
       AND NEW.status NOT IN ('RUNNING', 'CANCELLED') THEN
        RAISE EXCEPTION 'QUEUED experiments may only enter RUNNING or CANCELLED';
    END IF;

    IF OLD.status = 'RUNNING'
       AND NEW.status NOT IN ('SUCCEEDED', 'FAILED', 'CANCELLED') THEN
        RAISE EXCEPTION 'RUNNING experiments may only enter a terminal state';
    END IF;

    IF NEW.status = 'RUNNING' THEN
        NEW.started_at := COALESCE(NEW.started_at, clock_timestamp());
    END IF;

    IF NEW.status IN ('SUCCEEDED', 'FAILED', 'CANCELLED') THEN
        NEW.completed_at := COALESCE(NEW.completed_at, clock_timestamp());
    END IF;

    IF NEW.status = 'FAILED' AND
       (NEW.error_message IS NULL OR length(trim(NEW.error_message)) = 0) THEN
        RAISE EXCEPTION 'A failed experiment requires an error message';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER experiment_state_guard
BEFORE INSERT OR UPDATE OF status ON experiment
FOR EACH ROW
EXECUTE FUNCTION enforce_experiment_state_transition();

CREATE TABLE circuit_gate (
    experiment_id bigint NOT NULL REFERENCES experiment(experiment_id) ON DELETE CASCADE,
    sequence_number integer NOT NULL CHECK (sequence_number >= 0),
    gate_name text NOT NULL
        CHECK (gate_name IN ('H', 'X', 'Z', 'CNOT', 'CPHASE')),
    target_qubit integer NOT NULL CHECK (target_qubit >= 0),
    control_qubit integer CHECK (control_qubit >= 0),
    parameter_radians double precision,
    PRIMARY KEY (experiment_id, sequence_number),
    CHECK (control_qubit IS NULL OR control_qubit <> target_qubit),
    CHECK (
        (gate_name IN ('CNOT', 'CPHASE') AND control_qubit IS NOT NULL)
        OR
        (gate_name NOT IN ('CNOT', 'CPHASE') AND control_qubit IS NULL)
    ),
    CHECK (
        (gate_name = 'CPHASE' AND parameter_radians IS NOT NULL)
        OR
        (gate_name <> 'CPHASE' AND parameter_radians IS NULL)
    )
);

CREATE OR REPLACE FUNCTION validate_gate_register_positions()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_qubits integer;
    v_algorithm text;
    v_effective_qubits integer;
BEGIN
    SELECT qubit_count, algorithm_code
      INTO v_qubits, v_algorithm
      FROM experiment
     WHERE experiment_id = NEW.experiment_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown experiment %', NEW.experiment_id;
    END IF;

    v_effective_qubits := v_qubits;

    IF v_algorithm = 'PHASE_ESTIMATION' THEN
        v_effective_qubits := v_effective_qubits + 1;
    END IF;

    IF NEW.target_qubit >= v_effective_qubits THEN
        RAISE EXCEPTION 'Target qubit % exceeds register size %',
            NEW.target_qubit, v_effective_qubits;
    END IF;

    IF NEW.control_qubit IS NOT NULL
       AND NEW.control_qubit >= v_effective_qubits THEN
        RAISE EXCEPTION 'Control qubit % exceeds register size %',
            NEW.control_qubit, v_effective_qubits;
    END IF;

    IF NEW.parameter_radians IS NOT NULL
       AND NOT (
           NEW.parameter_radians > '-Infinity'::double precision
           AND NEW.parameter_radians < 'Infinity'::double precision
       ) THEN
        RAISE EXCEPTION 'Gate parameter must be finite';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER circuit_gate_register_guard
BEFORE INSERT OR UPDATE ON circuit_gate
FOR EACH ROW
EXECUTE FUNCTION validate_gate_register_positions();

CREATE TABLE measurement (
    measurement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id bigint NOT NULL REFERENCES experiment(experiment_id) ON DELETE CASCADE,
    shot_number integer NOT NULL CHECK (shot_number >= 1),
    bitstring text NOT NULL CHECK (bitstring ~ '^[01]+$'),
    outcome_probability double precision NOT NULL
        CHECK (
            outcome_probability >= 0
            AND outcome_probability <= 1
            AND outcome_probability < 'Infinity'::double precision
        ),
    measured_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (experiment_id, shot_number)
);

CREATE INDEX measurement_experiment_bitstring_idx
    ON measurement (experiment_id, bitstring);

CREATE OR REPLACE FUNCTION validate_measurement_record()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_qubits integer;
    v_status text;
BEGIN
    SELECT qubit_count, status
      INTO v_qubits, v_status
      FROM experiment
     WHERE experiment_id = NEW.experiment_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown experiment %', NEW.experiment_id;
    END IF;

    IF length(NEW.bitstring) <> v_qubits THEN
        RAISE EXCEPTION
            'Measurement width % does not match experiment width %',
            length(NEW.bitstring), v_qubits;
    END IF;

    IF v_status <> 'RUNNING' THEN
        RAISE EXCEPTION 'Measurements can only be recorded for RUNNING experiments';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER measurement_validation_guard
BEFORE INSERT OR UPDATE ON measurement
FOR EACH ROW
EXECUTE FUNCTION validate_measurement_record();

CREATE TABLE experiment_metric (
    experiment_id bigint NOT NULL REFERENCES experiment(experiment_id) ON DELETE CASCADE,
    metric_name text NOT NULL CHECK (length(trim(metric_name)) > 0),
    metric_value numeric NOT NULL,
    details jsonb NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(details) = 'object'),
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (experiment_id, metric_name)
);

CREATE TABLE experiment_event (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id bigint NOT NULL REFERENCES experiment(experiment_id) ON DELETE CASCADE,
    previous_status text,
    new_status text NOT NULL,
    event_time timestamptz NOT NULL DEFAULT clock_timestamp(),
    event_detail text
);

CREATE INDEX experiment_event_history_idx
    ON experiment_event (experiment_id, event_time);

CREATE OR REPLACE FUNCTION audit_experiment_status()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO experiment_event (
            experiment_id, previous_status, new_status, event_detail
        )
        VALUES (
            NEW.experiment_id, NULL, NEW.status, 'Experiment created'
        );
    ELSIF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO experiment_event (
            experiment_id, previous_status, new_status, event_detail
        )
        VALUES (
            NEW.experiment_id,
            OLD.status,
            NEW.status,
            COALESCE(NEW.error_message, 'Status changed')
        );
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER experiment_status_audit
AFTER INSERT OR UPDATE OF status ON experiment
FOR EACH ROW
EXECUTE FUNCTION audit_experiment_status();

-- Finalization writes numeric metrics and changes the status in one transaction.
CREATE OR REPLACE PROCEDURE finalize_experiment(
    p_experiment_id bigint,
    p_metrics jsonb
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_status text;
    v_key text;
    v_value jsonb;
BEGIN
    IF jsonb_typeof(p_metrics) <> 'object' THEN
        RAISE EXCEPTION 'Metrics must be supplied as a JSON object';
    END IF;

    SELECT status
      INTO v_status
      FROM experiment
     WHERE experiment_id = p_experiment_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Experiment % does not exist', p_experiment_id;
    END IF;

    IF v_status <> 'RUNNING' THEN
        RAISE EXCEPTION 'Only RUNNING experiments can be finalized';
    END IF;

    FOR v_key, v_value IN
        SELECT key, value
          FROM jsonb_each(p_metrics)
    LOOP
        IF jsonb_typeof(v_value) <> 'number' THEN
            RAISE EXCEPTION 'Metric % must have a numeric value', v_key;
        END IF;

        INSERT INTO experiment_metric (
            experiment_id, metric_name, metric_value
        )
        VALUES (
            p_experiment_id, v_key, (v_value #>> '{}')::numeric
        )
        ON CONFLICT (experiment_id, metric_name)
        DO UPDATE SET
            metric_value = EXCLUDED.metric_value,
            recorded_at = clock_timestamp();
    END LOOP;

    UPDATE experiment
       SET status = 'SUCCEEDED'
     WHERE experiment_id = p_experiment_id;
END;
$$;

CREATE VIEW v_experiment_summary AS
SELECT
    e.experiment_id,
    e.experiment_name,
    a.display_name AS algorithm,
    b.backend_name,
    b.backend_type,
    e.qubit_count,
    CASE
        WHEN e.algorithm_code = 'PHASE_ESTIMATION' THEN e.qubit_count + 1
        ELSE e.qubit_count
    END AS physical_qubit_requirement,
    e.shots,
    e.status,
    e.requested_by,
    e.created_at,
    e.started_at,
    e.completed_at,
    e.error_message,
    EXTRACT(EPOCH FROM (e.completed_at - e.started_at)) AS execution_seconds
FROM experiment e
JOIN algorithm a ON a.algorithm_code = e.algorithm_code
JOIN quantum_backend b ON b.backend_id = e.backend_id;

CREATE VIEW v_algorithm_performance AS
SELECT
    a.algorithm_code,
    a.display_name,
    count(DISTINCT e.experiment_id) AS experiment_count,
    count(DISTINCT e.experiment_id)
        FILTER (WHERE e.status = 'SUCCEEDED') AS successful_count,
    count(DISTINCT e.experiment_id)
        FILTER (WHERE e.status = 'FAILED') AS failed_count,
    round(
        avg(m.metric_value)
        FILTER (WHERE m.metric_name = 'success_probability'),
        6
    ) AS mean_success_probability,
    round(
        avg(m.metric_value)
        FILTER (WHERE m.metric_name = 'absolute_phase_error'),
        6
    ) AS mean_phase_error
FROM algorithm a
LEFT JOIN experiment e ON e.algorithm_code = a.algorithm_code
LEFT JOIN experiment_metric m ON m.experiment_id = e.experiment_id
GROUP BY a.algorithm_code, a.display_name;

-- This view describes execution readiness, not algorithmic correctness.
CREATE VIEW v_execution_eligibility AS
SELECT
    e.experiment_id,
    e.experiment_name,
    e.status,
    b.backend_name,
    b.is_active,
    CASE
        WHEN e.status <> 'QUEUED' THEN 'NOT_QUEUED'
        WHEN NOT b.is_active THEN 'BACKEND_INACTIVE'
        WHEN (
            e.qubit_count +
            CASE WHEN e.algorithm_code = 'PHASE_ESTIMATION' THEN 1 ELSE 0 END
        ) > b.max_qubits THEN 'INSUFFICIENT_CAPACITY'
        ELSE 'ELIGIBLE'
    END AS eligibility
FROM experiment e
JOIN quantum_backend b ON b.backend_id = e.backend_id;

