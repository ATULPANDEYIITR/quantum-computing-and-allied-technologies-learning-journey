-- Validation: inspect the algorithm parameters stored for each experiment.
SELECT
    experiment_id,
    algorithm_code,
    parameters,
    CASE
        WHEN algorithm_code = 'BERNSTEIN_VAZIRANI'
             AND parameters->>'secret' ~ '^[01]+$'
             AND length(parameters->>'secret') = qubit_count
            THEN 'VALID_SECRET'
        WHEN algorithm_code = 'GROVER'
             AND jsonb_typeof(parameters->'marked_states') = 'array'
            THEN 'VALID_MARKED_STATE_CONFIGURATION'
        WHEN algorithm_code = 'DEUTSCH_JOZSA'
             AND parameters->>'oracle' IN (
                 'constant-zero', 'constant-one', 'balanced-parity'
             )
            THEN 'VALID_ORACLE_CONFIGURATION'
        WHEN algorithm_code = 'PHASE_ESTIMATION'
             AND (parameters->>'phase')::numeric >= 0
             AND (parameters->>'phase')::numeric < 1
            THEN 'VALID_PHASE_CONFIGURATION'
        ELSE 'CHECK_CONFIGURATION'
    END AS configuration_check
FROM experiment
ORDER BY experiment_id;

