-- Compare observed loading against requested target capacity.
WITH occupancy AS (
    SELECT
        run_id,
        occupied_sites,
        target_count,
        CASE
            WHEN occupied_sites >= target_count THEN TRUE
            ELSE FALSE
        END AS atom_count_sufficient
    FROM neutral_atom_lab.v_run_occupancy
)
SELECT
    run_id,
    occupied_sites,
    target_count,
    atom_count_sufficient,
    occupied_sites - target_count AS atom_surplus
FROM occupancy
ORDER BY run_id;
