-- Neutral-atom computing: optical trapping and atom-array workflow.
--
-- PostgreSQL relational model for:
--   * Gaussian tweezer calibration
--   * Rectangular optical tweezer arrays
--   * Laboratory runs and environmental telemetry
--   * Fluorescence-based atom occupancy observations
--   * Rearrangement plans and individual atom transfers
--   * Run validation, state transitions, and readiness reporting
--
-- This script creates a reusable schema. It does not drop existing data.

BEGIN;

CREATE SCHEMA IF NOT EXISTS neutral_atom_lab;

DO $$
BEGIN
    CREATE TYPE neutral_atom_lab.run_state AS ENUM (
        'draft',
        'validated',
        'loaded',
        'rearranged',
        'ready',
        'failed'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END;
$$;

DO $$
BEGIN
    CREATE TYPE neutral_atom_lab.plan_state AS ENUM (
        'planned',
        'completed',
        'failed'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END;
$$;

-- Optical parameters are stored in SI units.
CREATE TABLE IF NOT EXISTS neutral_atom_lab.trap_calibration (
    calibration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calibration_name TEXT NOT NULL UNIQUE,
    wavelength_m DOUBLE PRECISION NOT NULL CHECK (wavelength_m > 0),
    waist_m DOUBLE PRECISION NOT NULL CHECK (waist_m > 0),
    trap_depth_j DOUBLE PRECISION NOT NULL CHECK (trap_depth_j > 0),
    atomic_mass_kg DOUBLE PRECISION NOT NULL CHECK (atomic_mass_kg > 0),
    beam_power_w DOUBLE PRECISION NOT NULL CHECK (beam_power_w > 0),
    calibrated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valid_until TIMESTAMPTZ NOT NULL,
    CHECK (valid_until > calibrated_at)
);

CREATE TABLE IF NOT EXISTS neutral_atom_lab.tweezer_array (
    array_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    array_name TEXT NOT NULL UNIQUE,
    row_count INTEGER NOT NULL CHECK (row_count > 0),
    column_count INTEGER NOT NULL CHECK (column_count > 0),
    spacing_m DOUBLE PRECISION NOT NULL CHECK (spacing_m > 0),
    calibration_id BIGINT NOT NULL
        REFERENCES neutral_atom_lab.trap_calibration(calibration_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS neutral_atom_lab.array_site (
    site_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    array_id BIGINT NOT NULL
        REFERENCES neutral_atom_lab.tweezer_array(array_id)
        ON DELETE CASCADE,
    row_index INTEGER NOT NULL CHECK (row_index >= 0),
    column_index INTEGER NOT NULL CHECK (column_index >= 0),
    x_m DOUBLE PRECISION NOT NULL CHECK (x_m >= 0),
    y_m DOUBLE PRECISION NOT NULL CHECK (y_m >= 0),
    UNIQUE (array_id, row_index, column_index),
    UNIQUE (array_id, x_m, y_m),
    UNIQUE (site_id, array_id)
);

CREATE TABLE IF NOT EXISTS neutral_atom_lab.lab_run (
    run_id BIGINT PRIMARY KEY,
    run_name TEXT NOT NULL UNIQUE,
    array_id BIGINT NOT NULL
        REFERENCES neutral_atom_lab.tweezer_array(array_id),
    target_count INTEGER NOT NULL CHECK (target_count > 0),
    state neutral_atom_lab.run_state NOT NULL DEFAULT 'draft',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (run_id, array_id)
);

CREATE TABLE IF NOT EXISTS neutral_atom_lab.run_environment (
    run_id BIGINT PRIMARY KEY
        REFERENCES neutral_atom_lab.lab_run(run_id) ON DELETE CASCADE,
    vacuum_pressure_pa DOUBLE PRECISION NOT NULL
        CHECK (vacuum_pressure_pa >= 0),
    interlock_healthy BOOLEAN NOT NULL,
    emergency_stop BOOLEAN NOT NULL DEFAULT FALSE,
    measured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Each site has one observation per run. Occupancy is a measured outcome,
-- not a theoretical loading probability.
CREATE TABLE IF NOT EXISTS neutral_atom_lab.site_observation (
    run_id BIGINT NOT NULL,
    array_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL,
    atom_present BOOLEAN NOT NULL,
    detection_confidence DOUBLE PRECISION NOT NULL
        CHECK (detection_confidence >= 0 AND detection_confidence <= 1),
    observed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (run_id, site_id),
    FOREIGN KEY (run_id, array_id)
        REFERENCES neutral_atom_lab.lab_run(run_id, array_id)
        ON DELETE CASCADE,
    FOREIGN KEY (site_id, array_id)
        REFERENCES neutral_atom_lab.array_site(site_id, array_id)
);

CREATE TABLE IF NOT EXISTS neutral_atom_lab.rearrangement_plan (
    plan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    array_id BIGINT NOT NULL,
    target_count INTEGER NOT NULL CHECK (target_count > 0),
    state neutral_atom_lab.plan_state NOT NULL DEFAULT 'planned',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    UNIQUE (run_id),
    FOREIGN KEY (run_id, array_id)
        REFERENCES neutral_atom_lab.lab_run(run_id, array_id)
        ON DELETE CASCADE,
    CHECK (
        (state = 'completed' AND completed_at IS NOT NULL)
        OR
        (state <> 'completed' AND completed_at IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS neutral_atom_lab.transfer_move (
    plan_id BIGINT NOT NULL
        REFERENCES neutral_atom_lab.rearrangement_plan(plan_id)
        ON DELETE CASCADE,
    array_id BIGINT NOT NULL,
    source_site_id BIGINT NOT NULL,
    target_site_id BIGINT NOT NULL,
    distance_m DOUBLE PRECISION NOT NULL CHECK (distance_m >= 0),
    PRIMARY KEY (plan_id, source_site_id),
    UNIQUE (plan_id, target_site_id),
    FOREIGN KEY (source_site_id, array_id)
        REFERENCES neutral_atom_lab.array_site(site_id, array_id),
    FOREIGN KEY (target_site_id, array_id)
        REFERENCES neutral_atom_lab.array_site(site_id, array_id)
);

CREATE INDEX IF NOT EXISTS idx_array_site_grid
    ON neutral_atom_lab.array_site(array_id, row_index, column_index);

CREATE INDEX IF NOT EXISTS idx_lab_run_state
    ON neutral_atom_lab.lab_run(state, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_observation_occupied
    ON neutral_atom_lab.site_observation(run_id, site_id)
    WHERE atom_present = TRUE;

CREATE INDEX IF NOT EXISTS idx_transfer_move_plan
    ON neutral_atom_lab.transfer_move(plan_id);

CREATE INDEX IF NOT EXISTS idx_calibration_validity
    ON neutral_atom_lab.trap_calibration(valid_until);

COMMENT ON TABLE neutral_atom_lab.trap_calibration IS
    'Gaussian tweezer calibration values, with all optical quantities in SI units.';

COMMENT ON TABLE neutral_atom_lab.site_observation IS
    'Fluorescence-imaging occupancy outcomes for individual tweezer sites.';

COMMENT ON TABLE neutral_atom_lab.transfer_move IS
    'Unique source-to-target assignments associated with a rearrangement plan.';

-- Verify that site coordinates agree with the declared rectangular lattice.
CREATE OR REPLACE FUNCTION neutral_atom_lab.validate_site_geometry()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_spacing DOUBLE PRECISION;
    v_rows INTEGER;
    v_columns INTEGER;
BEGIN
    SELECT spacing_m, row_count, column_count
    INTO v_spacing, v_rows, v_columns
    FROM neutral_atom_lab.tweezer_array
    WHERE array_id = NEW.array_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown tweezer array: %', NEW.array_id;
    END IF;

    IF NEW.row_index >= v_rows OR NEW.column_index >= v_columns THEN
        RAISE EXCEPTION 'Site index is outside the configured array.';
    END IF;

    IF abs(NEW.x_m - NEW.column_index * v_spacing) > 1e-12
       OR abs(NEW.y_m - NEW.row_index * v_spacing) > 1e-12 THEN
        RAISE EXCEPTION 'Site coordinates do not match the array lattice.';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_site_geometry
    ON neutral_atom_lab.array_site;

CREATE TRIGGER trg_validate_site_geometry
BEFORE INSERT OR UPDATE OF array_id, row_index, column_index, x_m, y_m
ON neutral_atom_lab.array_site
FOR EACH ROW
EXECUTE FUNCTION neutral_atom_lab.validate_site_geometry();

-- Enforce the run lifecycle independently of application code.
CREATE OR REPLACE FUNCTION neutral_atom_lab.enforce_run_state_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.state = OLD.state THEN
        NEW.updated_at := CURRENT_TIMESTAMP;
        RETURN NEW;
    END IF;

    IF NEW.state = 'failed' AND OLD.state <> 'ready' THEN
        NEW.updated_at := CURRENT_TIMESTAMP;
        RETURN NEW;
    END IF;

    IF (OLD.state = 'draft' AND NEW.state = 'validated')
       OR (OLD.state = 'validated' AND NEW.state = 'loaded')
       OR (OLD.state = 'loaded' AND NEW.state = 'rearranged')
       OR (OLD.state = 'rearranged' AND NEW.state = 'ready') THEN
        NEW.updated_at := CURRENT_TIMESTAMP;
        RETURN NEW;
    END IF;

    RAISE EXCEPTION
        'Invalid laboratory run transition: % -> %',
        OLD.state,
        NEW.state;
END;
$$;

DROP TRIGGER IF EXISTS trg_run_state_transition
    ON neutral_atom_lab.lab_run;

CREATE TRIGGER trg_run_state_transition
BEFORE UPDATE OF state
ON neutral_atom_lab.lab_run
FOR EACH ROW
EXECUTE FUNCTION neutral_atom_lab.enforce_run_state_transition();

-- Prevent a transfer from using an empty source site.
-- Composite foreign keys separately enforce array membership.
CREATE OR REPLACE FUNCTION neutral_atom_lab.validate_transfer_source()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_run_id BIGINT;
    v_atom_present BOOLEAN;
    v_plan_state neutral_atom_lab.plan_state;
BEGIN
    SELECT run_id, state
    INTO v_run_id, v_plan_state
    FROM neutral_atom_lab.rearrangement_plan
    WHERE plan_id = NEW.plan_id
      AND array_id = NEW.array_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Rearrangement plan does not exist for this array.';
    END IF;

    IF v_plan_state <> 'planned' THEN
        RAISE EXCEPTION 'Transfers can only be added to a planned rearrangement.';
    END IF;

    SELECT atom_present
    INTO v_atom_present
    FROM neutral_atom_lab.site_observation
    WHERE run_id = v_run_id
      AND array_id = NEW.array_id
      AND site_id = NEW.source_site_id;

    IF NOT FOUND OR v_atom_present IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION
            'Source site % has no observed atom in run %.',
            NEW.source_site_id,
            v_run_id;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_transfer_source
    ON neutral_atom_lab.transfer_move;

CREATE TRIGGER trg_validate_transfer_source
BEFORE INSERT OR UPDATE
ON neutral_atom_lab.transfer_move
FOR EACH ROW
EXECUTE FUNCTION neutral_atom_lab.validate_transfer_source();

-- Calculate harmonic trap frequencies near the minimum of a Gaussian trap.
-- For Rayleigh range zR = pi*w0^2/lambda:
-- radial omega^2 = 4*U0/(m*w0^2)
-- axial omega^2  = 2*U0/(m*zR^2)
CREATE OR REPLACE FUNCTION neutral_atom_lab.trap_frequencies(
    p_calibration_id BIGINT
)
RETURNS TABLE (
    rayleigh_range_m DOUBLE PRECISION,
    radial_frequency_hz DOUBLE PRECISION,
    axial_frequency_hz DOUBLE PRECISION
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        pi() * c.waist_m * c.waist_m / c.wavelength_m,
        sqrt(
            4.0 * c.trap_depth_j /
            (c.atomic_mass_kg * c.waist_m * c.waist_m)
        ) / (2.0 * pi()),
        sqrt(
            2.0 * c.trap_depth_j /
            (
                c.atomic_mass_kg *
                power(
                    pi() * c.waist_m * c.waist_m / c.wavelength_m,
                    2
                )
            )
        ) / (2.0 * pi())
    FROM neutral_atom_lab.trap_calibration AS c
    WHERE c.calibration_id = p_calibration_id;
$$;

-- Return preflight eligibility and all detected reasons.
-- A run must be in draft state before it can be validated.
CREATE OR REPLACE FUNCTION neutral_atom_lab.run_preflight(
    p_run_id BIGINT
)
RETURNS TABLE (
    eligible BOOLEAN,
    reasons TEXT[],
    occupied_sites BIGINT,
    observed_sites BIGINT,
    total_sites BIGINT
)
LANGUAGE sql
STABLE
AS $$
    WITH metrics AS (
        SELECT
            r.run_id,
            r.state,
            r.target_count,
            a.row_count,
            a.column_count,
            c.valid_until,
            c.calibration_id,
            e.run_id AS environment_run_id,
            e.vacuum_pressure_pa,
            e.interlock_healthy,
            e.emergency_stop,
            count(o.site_id) AS observation_count,
            count(o.site_id) FILTER (WHERE o.atom_present) AS occupied_count,
            (a.row_count::BIGINT * a.column_count::BIGINT) AS site_capacity
        FROM neutral_atom_lab.lab_run AS r
        JOIN neutral_atom_lab.tweezer_array AS a
          ON a.array_id = r.array_id
        JOIN neutral_atom_lab.trap_calibration AS c
          ON c.calibration_id = a.calibration_id
        LEFT JOIN neutral_atom_lab.run_environment AS e
          ON e.run_id = r.run_id
        LEFT JOIN neutral_atom_lab.site_observation AS o
          ON o.run_id = r.run_id
         AND o.array_id = r.array_id
        WHERE r.run_id = p_run_id
        GROUP BY
            r.run_id,
            r.state,
            r.target_count,
            a.row_count,
            a.column_count,
            c.valid_until,
            c.calibration_id,
            e.run_id,
            e.vacuum_pressure_pa,
            e.interlock_healthy,
            e.emergency_stop
    )
    SELECT
        (
            state = 'draft'
            AND valid_until > CURRENT_TIMESTAMP
            AND environment_run_id IS NOT NULL
            AND interlock_healthy IS TRUE
            AND emergency_stop IS FALSE
            AND vacuum_pressure_pa <= 1e-7
            AND observation_count = site_capacity
            AND occupied_count >= target_count
        ) AS eligible,
        array_remove(ARRAY[
            CASE WHEN state <> 'draft'
                THEN 'Run is not in draft state.' END,
            CASE WHEN valid_until <= CURRENT_TIMESTAMP
                THEN 'Trap calibration has expired.' END,
            CASE WHEN environment_run_id IS NULL
                THEN 'Environmental telemetry is missing.' END,
            CASE WHEN interlock_healthy IS DISTINCT FROM TRUE
                THEN 'Laser interlock is not healthy.' END,
            CASE WHEN emergency_stop IS DISTINCT FROM FALSE
                THEN 'Emergency-stop condition is active.' END,
            CASE WHEN vacuum_pressure_pa IS NULL OR vacuum_pressure_pa > 1e-7
                THEN 'Vacuum pressure exceeds the facility threshold.' END,
            CASE WHEN observation_count <> site_capacity
                THEN 'Occupancy observations do not cover every array site.' END,
            CASE WHEN occupied_count < target_count
                THEN 'Insufficient observed atoms for the requested targets.' END
        ], NULL) AS reasons,
        occupied_count,
        observation_count,
        site_capacity
    FROM metrics;
$$;

-- Validate calibration, environment, and occupancy coverage before loading.
CREATE OR REPLACE PROCEDURE neutral_atom_lab.validate_run(
    p_run_id BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_eligible BOOLEAN;
    v_reasons TEXT[];
BEGIN
    SELECT f.eligible, f.reasons
    INTO v_eligible, v_reasons
    FROM neutral_atom_lab.run_preflight(p_run_id) AS f;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Laboratory run % does not exist.', p_run_id;
    END IF;

    IF NOT v_eligible THEN
        RAISE EXCEPTION
            'Run % failed preflight: %',
            p_run_id,
            array_to_string(v_reasons, ' ');
    END IF;

    UPDATE neutral_atom_lab.lab_run
    SET state = 'validated'
    WHERE run_id = p_run_id;
END;
$$;

CREATE OR REPLACE PROCEDURE neutral_atom_lab.mark_loaded(
    p_run_id BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_state neutral_atom_lab.run_state;
    v_expected_sites BIGINT;
    v_observed_sites BIGINT;
BEGIN
    SELECT r.state, a.row_count::BIGINT * a.column_count::BIGINT
    INTO v_state, v_expected_sites
    FROM neutral_atom_lab.lab_run AS r
    JOIN neutral_atom_lab.tweezer_array AS a
      ON a.array_id = r.array_id
    WHERE r.run_id = p_run_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Laboratory run % does not exist.', p_run_id;
    END IF;

    IF v_state <> 'validated' THEN
        RAISE EXCEPTION 'Run % must be validated before loading.', p_run_id;
    END IF;

    SELECT count(*)
    INTO v_observed_sites
    FROM neutral_atom_lab.site_observation
    WHERE run_id = p_run_id;

    IF v_observed_sites <> v_expected_sites THEN
        RAISE EXCEPTION
            'Run % has % observations; expected %.',
            p_run_id,
            v_observed_sites,
            v_expected_sites;
    END IF;

    UPDATE neutral_atom_lab.lab_run
    SET state = 'loaded'
    WHERE run_id = p_run_id;
END;
$$;

-- Create a deterministic baseline plan:
-- source atoms are ranked in descending grid order and target sites in
-- ascending grid order. This SQL plan is easy to audit but is not a
-- globally optimal transport assignment.
CREATE OR REPLACE PROCEDURE neutral_atom_lab.build_rearrangement_plan(
    p_run_id BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_array_id BIGINT;
    v_target_count INTEGER;
    v_state neutral_atom_lab.run_state;
    v_occupied_count BIGINT;
    v_plan_id BIGINT;
BEGIN
    SELECT r.array_id, r.target_count, r.state
    INTO v_array_id, v_target_count, v_state
    FROM neutral_atom_lab.lab_run AS r
    WHERE r.run_id = p_run_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Laboratory run % does not exist.', p_run_id;
    END IF;

    IF v_state <> 'loaded' THEN
        RAISE EXCEPTION 'Run % must be loaded before rearrangement.', p_run_id;
    END IF;

    SELECT count(*)
    INTO v_occupied_count
    FROM neutral_atom_lab.site_observation
    WHERE run_id = p_run_id
      AND atom_present = TRUE;

    IF v_occupied_count < v_target_count THEN
        RAISE EXCEPTION
            'Insufficient atoms: % observed for % targets.',
            v_occupied_count,
            v_target_count;
    END IF;

    INSERT INTO neutral_atom_lab.rearrangement_plan (
        run_id,
        array_id,
        target_count,
        state
    )
    VALUES (
        p_run_id,
        v_array_id,
        v_target_count,
        'planned'
    )
    RETURNING plan_id INTO v_plan_id;

    WITH ranked_sources AS (
        SELECT
            o.site_id,
            s.row_index,
            s.column_index,
            row_number() OVER (
                ORDER BY s.row_index DESC, s.column_index DESC
            ) AS position_rank
        FROM neutral_atom_lab.site_observation AS o
        JOIN neutral_atom_lab.array_site AS s
          ON s.site_id = o.site_id
         AND s.array_id = o.array_id
        WHERE o.run_id = p_run_id
          AND o.atom_present = TRUE
    ),
    ranked_targets AS (
        SELECT
            s.site_id,
            s.row_index,
            s.column_index,
            row_number() OVER (
                ORDER BY s.row_index, s.column_index
            ) AS position_rank
        FROM neutral_atom_lab.array_site AS s
        WHERE s.array_id = v_array_id
    )
    INSERT INTO neutral_atom_lab.transfer_move (
        plan_id,
        array_id,
        source_site_id,
        target_site_id,
        distance_m
    )
    SELECT
        v_plan_id,
        v_array_id,
        source.site_id,
        target.site_id,
        sqrt(
            power(source_site.x_m - target_site.x_m, 2) +
            power(source_site.y_m - target_site.y_m, 2)
        )
    FROM ranked_sources AS source
    JOIN ranked_targets AS target
      ON target.position_rank = source.position_rank
    JOIN neutral_atom_lab.array_site AS source_site
      ON source_site.site_id = source.site_id
     AND source_site.array_id = v_array_id
    JOIN neutral_atom_lab.array_site AS target_site
      ON target_site.site_id = target.site_id
     AND target_site.array_id = v_array_id
    WHERE source.position_rank <= v_target_count;

    IF (
        SELECT count(*)
        FROM neutral_atom_lab.transfer_move
        WHERE plan_id = v_plan_id
    ) <> v_target_count THEN
        RAISE EXCEPTION 'Plan % did not assign every target.', v_plan_id;
    END IF;

    UPDATE neutral_atom_lab.lab_run
    SET state = 'rearranged'
    WHERE run_id = p_run_id;
END;
$$;

CREATE OR REPLACE PROCEDURE neutral_atom_lab.complete_rearrangement(
    p_plan_id BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_run_id BIGINT;
    v_target_count INTEGER;
    v_move_count BIGINT;
    v_plan_state neutral_atom_lab.plan_state;
BEGIN
    SELECT run_id, target_count, state
    INTO v_run_id, v_target_count, v_plan_state
    FROM neutral_atom_lab.rearrangement_plan
    WHERE plan_id = p_plan_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Rearrangement plan % does not exist.', p_plan_id;
    END IF;

    IF v_plan_state <> 'planned' THEN
        RAISE EXCEPTION 'Plan % is not in planned state.', p_plan_id;
    END IF;

    SELECT count(*)
    INTO v_move_count
    FROM neutral_atom_lab.transfer_move
    WHERE plan_id = p_plan_id;

    IF v_move_count <> v_target_count THEN
        RAISE EXCEPTION
            'Plan % has % moves; expected %.',
            p_plan_id,
            v_move_count,
            v_target_count;
    END IF;

    UPDATE neutral_atom_lab.rearrangement_plan
    SET state = 'completed',
        completed_at = CURRENT_TIMESTAMP
    WHERE plan_id = p_plan_id;

    UPDATE neutral_atom_lab.lab_run
    SET state = 'ready'
    WHERE run_id = v_run_id;
END;
$$;

-- Occupancy aggregation for run-level reporting.
CREATE OR REPLACE VIEW neutral_atom_lab.v_run_occupancy AS
SELECT
    r.run_id,
    r.run_name,
    r.state,
    a.array_name,
    a.row_count,
    a.column_count,
    a.row_count * a.column_count AS total_sites,
    count(o.site_id) AS observed_sites,
    count(o.site_id) FILTER (WHERE o.atom_present) AS occupied_sites,
    count(o.site_id) FILTER (WHERE NOT o.atom_present) AS vacant_sites,
    CASE
        WHEN count(o.site_id) > 0
        THEN count(o.site_id) FILTER (WHERE o.atom_present)::DOUBLE PRECISION
             / count(o.site_id)
        ELSE NULL
    END AS observed_loading_fraction,
    r.target_count
FROM neutral_atom_lab.lab_run AS r
JOIN neutral_atom_lab.tweezer_array AS a
  ON a.array_id = r.array_id
LEFT JOIN neutral_atom_lab.site_observation AS o
  ON o.run_id = r.run_id
 AND o.array_id = r.array_id
GROUP BY
    r.run_id,
    r.run_name,
    r.state,
    a.array_name,
    a.row_count,
    a.column_count,
    r.target_count;

-- Transport reporting is distinct from quantum-state fidelity.
CREATE OR REPLACE VIEW neutral_atom_lab.v_rearrangement_report AS
SELECT
    p.plan_id,
    p.run_id,
    p.state AS plan_state,
    p.target_count,
    count(m.source_site_id) AS assigned_moves,
    COALESCE(sum(m.distance_m), 0.0) AS total_transport_distance_m,
    COALESCE(avg(m.distance_m), 0.0) AS average_transport_distance_m,
    count(m.source_site_id) FILTER (WHERE m.distance_m = 0) AS stationary_assignments
FROM neutral_atom_lab.rearrangement_plan AS p
LEFT JOIN neutral_atom_lab.transfer_move AS m
  ON m.plan_id = p.plan_id
GROUP BY p.plan_id, p.run_id, p.state, p.target_count;

-- Sample calibration and a 4 x 4 array.
INSERT INTO neutral_atom_lab.trap_calibration (
    calibration_id,
    calibration_name,
